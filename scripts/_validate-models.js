process.env.NODE_ENV='test';
require('../lib/promise-shim');
const db=require('../lib/model/db');
(async()=>{
  await db.sequelize.sync();
  const [tables]=await db.sequelize.query("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name");
  console.log('TABLES:', tables.map(t=>t.name).join(', '));
  const company=await db.Company.create_default_company({name:'Acme',country_code:'UK',timezone:'Europe/London'});
  console.log('COMPANY created id=',company.id);
  const depts=await company.getDepartments();
  console.log('DEPARTMENTS:', depts.map(d=>d.name).join(','));
  const lts=await company.getLeave_types();
  console.log('LEAVE_TYPES count=',lts.length);
  const bh=await company.getBank_holidays();
  console.log('BANK_HOLIDAYS count=',bh.length);
  const user=await db.User.register_new_admin_user({email:'admin@acme.test',password:'Passw0rd!',name:'Admin',lastname:'Acme',company_name:'Acme2',country_code:'UK',timezone:'Europe/London'});
  console.log('USER created id=',user.id,'admin=',user.admin,'companyId=',user.companyId);
  const found=await db.User.find_by_email('admin@acme.test');
  console.log('find_by_email OK id=',found && found.id);
  const active=await db.User.findAll({where: db.User.get_active_user_filter()});
  console.log('active users ($or operators) count=',active.length);
  await db.sequelize.close();
  console.log('VALIDATION_OK');
})().catch(e=>{console.error('VALIDATION_FAIL', e); process.exit(1);});
